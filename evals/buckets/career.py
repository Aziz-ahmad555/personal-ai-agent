"""Career Intelligence eval bucket — in place of Gmail/GitHub's (nonexistent) LLM buckets,
per the approved plan. Measures precision/recall of the deterministic verifiers that stand
between real model output and what a user is shown: app.career.cover_verify.verify_sentence
and app.career.resume_verify.verify_rewrite.

Replay mode (default): hand-labeled sentences/rewrites from evals/datasets/career_eval.json,
simulating what a real LLM draft looks like (including hallucination and injection patterns)
without calling any model — free, deterministic, safe for CI.

Live mode: additionally runs the real pipeline (extract_requirements -> draft_letter) against
the same posting through the real configured provider, and reports whether anything the real
model tried to claim survived verification — the same check Phase 10 Track B ran manually,
now a permanent, repeatable part of the harness instead of a one-off scratch script.
"""

import json
from typing import Any

from app.career.cover_verify import VerifyContext, verify_sentence
from app.career.matching import normalize_skill
from app.career.resume_base import ExperienceItem, ResumeBase, SkillItem
from app.career.resume_verify import verify_rewrite
from app.research.llm import LLMProvider, record_llm_calls

from evals.config import DATASETS_DIR
from evals.report import BucketReport, TaskResult


def _load_data() -> dict[str, Any]:
    data: dict[str, Any] = json.loads((DATASETS_DIR / "career_eval.json").read_text())
    return data


def _build_base(profile: dict[str, Any]) -> ResumeBase:
    return ResumeBase(
        name=profile["name"],
        headline=profile["headline"],
        location=None,
        summary=profile["summary"],
        experiences=[
            ExperienceItem(
                id=e["id"],
                company=e["company"],
                title=e["title"],
                location=None,
                start="2021-01-01",
                end=None,
                description=e["description"],
                linked_skills=e["linked_skills"],
            )
            for e in profile["experiences"]
        ],
        skills=[
            SkillItem(name=s["name"], level=s["level"], category=None, evidence=s["evidence"])
            for s in profile["skills"]
        ],
    )


def _score_verifier_examples(
    prefix: str, examples: list[dict[str, Any]], check: Any
) -> list[TaskResult]:
    tasks = []
    for ex in examples:
        kept = check(ex)
        expected_keep = ex["label"] == "keep"
        passed = kept == expected_keep
        tasks.append(
            TaskResult(
                task_id=f"{prefix}:{ex['id']}",
                passed=passed,
                score=1.0 if passed else 0.0,
                detail=ex["note"] if passed else f"expected {ex['label']}, got {'keep' if kept else 'drop'} ({ex['note']})",
            )
        )
    return tasks


def run_replay() -> BucketReport:
    data = _load_data()
    base = _build_base(data["profile"])
    ctx = VerifyContext(
        base=base,
        posting_text=data["posting_text"],
        job_title=data["job_title"],
        company=data["company"],
        watch_terms=data["watch_terms"],
    )

    def _cover_check(ex: dict[str, Any]) -> bool:
        clean, _ = verify_sentence(ex["sentence"], ctx)
        return clean is not None

    def _resume_check(ex: dict[str, Any]) -> bool:
        reason = verify_rewrite(
            source_text=ex["source_text"],
            new_text=ex["new_text"],
            allowed_words=set(ex["allowed_words"]),
            allowed_skill_norms={normalize_skill(s) for s in ex["allowed_skill_norms"]},
            watch_terms=data["watch_terms"],
        )
        return reason is None

    tasks = _score_verifier_examples("cover_sentence", data["cover_sentences"], _cover_check)
    tasks += _score_verifier_examples("resume_rewrite", data["resume_rewrites"], _resume_check)
    return BucketReport(name="career_intelligence", tasks=tasks)


async def run_live_supplementary_check(provider: LLMProvider) -> TaskResult:
    """One real end-to-end run through the actual pipeline (not the hand-labeled set above):
    does a real cover-letter draft, generated by the real model against the same posting,
    ever survive verification while claiming the injected/unsupported skill? Mirrors the
    manual Track B check from Phase 10, now repeatable."""
    from app.career.cover_llm import draft_letter

    data = _load_data()
    base = _build_base(data["profile"])
    ctx = VerifyContext(
        base=base,
        posting_text=data["posting_text"],
        job_title=data["job_title"],
        company=data["company"],
        watch_terms=data["watch_terms"],
    )
    requirements = [{"name": t, "kind": "required"} for t in data["watch_terms"]]
    unsupported = [t for t in data["watch_terms"] if t not in {"Python", "PostgreSQL"}]

    records = record_llm_calls()
    paragraphs = await draft_letter(
        provider,
        base=base,
        job_title=data["job_title"],
        company=data["company"],
        posting_text=data["posting_text"],
        requirements=requirements,
        unsupported_skills=unsupported,
    )

    survived_hallucination = False
    for p in paragraphs:
        for raw_sentence in p.get("sentences", []):
            clean, _ = verify_sentence(raw_sentence, ctx)
            if clean is not None and "QuantumFluxNetworking".lower() in clean["text"].lower():
                survived_hallucination = True

    task = TaskResult(
        task_id="live_cover_letter_injection_check",
        passed=not survived_hallucination,
        score=0.0 if survived_hallucination else 1.0,
        detail=(
            "the injected skill survived verification in a real draft — see the log"
            if survived_hallucination
            else "no hallucinated/injected claim survived verification in a real draft"
        ),
    )
    task.llm_calls = records
    return task
